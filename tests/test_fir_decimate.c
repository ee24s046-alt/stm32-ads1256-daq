/**
 * @file test_fir_decimate.c
 * @brief The tests that make the polyphase and alias-rejection claims real.
 *
 * Two of these are the point of the whole file:
 *
 *   test_polyphase_equals_naive - asserts that the 4x-cheaper polyphase
 *   implementation produces output *bit-identical* to filter-then-discard. The
 *   optimisation is only worth claiming if it is provably free, and a branch
 *   indexing error produces output that still looks like filtered data.
 *
 *   test_alias_rejection - measures, rather than asserts from the design
 *   script, that an out-of-band tone which would fold into the passband is
 *   attenuated by more than 40 dB.
 */
#include "test_harness.h"
#include "fir_decimate.h"
#include "fir_coeffs.h"
#include <math.h>

#ifndef M_PI
#define M_PI 3.14159265358979323846
#endif

#define N_IN 4096U

static int32_t s_in[N_IN];
static int32_t s_poly[N_IN / FIR_DECIM_M + 4U];
static int32_t s_ref[N_IN / FIR_DECIM_M + 4U];

static uint32_t run_polyphase(const int32_t *in, uint32_t n_in, int32_t *out)
{
    fir_decim_t f;
    uint32_t produced = 0U;
    int32_t y;

    fir_decim_reset(&f);
    for (uint32_t i = 0U; i < n_in; i++) {
        if (fir_decim_push(&f, in[i], &y)) {
            out[produced] = y;
            produced++;
        }
    }
    return produced;
}

/** RMS of a decimated tone, skipping the filter's transient. */
static double out_rms(const int32_t *y, uint32_t n, uint32_t skip)
{
    double acc = 0.0;
    uint32_t cnt = 0U;

    for (uint32_t i = skip; i < n; i++) {
        acc += (double)y[i] * (double)y[i];
        cnt++;
    }
    return (cnt != 0U) ? sqrt(acc / (double)cnt) : 0.0;
}

static void fill_tone(int32_t *buf, uint32_t n, double hz, double amp)
{
    for (uint32_t i = 0U; i < n; i++) {
        buf[i] = (int32_t)lrint(amp * sin(2.0 * M_PI * hz * (double)i
                                          / (double)FIR_FS_IN_HZ));
    }
}

/* ---------------------------------------------------------------------- */
static void test_taps_are_unity_dc_gain(void)
{
    int32_t sum = 0;

    TEST("taps sum to exactly Q15 - unity DC gain, not approximately");
    for (uint32_t i = 0U; i < FIR_NUM_TAPS; i++) {
        sum += k_fir_taps_q15[i];
    }
    CHECK_EQ(sum, 32768);

    /* Linear phase requires a symmetric impulse response. */
    for (uint32_t i = 0U; i < (FIR_NUM_TAPS / 2U); i++) {
        CHECK_EQ(k_fir_taps_q15[i], k_fir_taps_q15[FIR_NUM_TAPS - 1U - i]);
    }
}

static void test_dc_passes_through_unchanged(void)
{
    TEST("a DC input emerges at the same level (unity gain, no droop)");

    for (uint32_t i = 0U; i < N_IN; i++) {
        s_in[i] = 1000000;
    }
    const uint32_t n = run_polyphase(s_in, N_IN, s_poly);

    CHECK_EQ(n, N_IN / FIR_DECIM_M);
    /* After the transient, every output must be the input, within rounding. */
    for (uint32_t i = FIR_NUM_TAPS; i < n; i++) {
        CHECK(labs((long)s_poly[i] - 1000000L) <= 1);
    }
}

static void test_polyphase_equals_naive(void)
{
    TEST("polyphase output is BIT-IDENTICAL to naive filter-then-discard");

    /* Broadband content so every tap is exercised, not just the centre few. */
    for (uint32_t i = 0U; i < N_IN; i++) {
        s_in[i] = (int32_t)((i * 2654435761U) % 2000001U) - 1000000;
    }

    const uint32_t n_poly = run_polyphase(s_in, N_IN, s_poly);
    uint32_t n_ref = 0U;
    fir_decim_reference(s_in, N_IN, s_ref, &n_ref);

    CHECK_EQ(n_poly, n_ref);
    for (uint32_t i = 0U; i < n_ref; i++) {
        CHECK_EQ(s_poly[i], s_ref[i]);
    }
}

static void test_golden_vector(void)
{
    int32_t out[FIR_GOLDEN_OUT_LEN + 4U];
    uint32_t n;

    TEST("output matches the vector generated by tools/design_filter.py");

    n = run_polyphase(k_fir_golden_in, FIR_GOLDEN_IN_LEN, out);
    CHECK_EQ(n, FIR_GOLDEN_OUT_LEN);
    for (uint32_t i = 0U; i < FIR_GOLDEN_OUT_LEN; i++) {
        CHECK_EQ(out[i], k_fir_golden_out[i]);
    }
}

static void test_passband_tone_survives(void)
{
    TEST("a 1 kHz in-band tone passes with less than 0.5 dB of loss");

    const double amp = 1000000.0;
    fill_tone(s_in, N_IN, 1000.0, amp);
    const uint32_t n = run_polyphase(s_in, N_IN, s_poly);

    const double rms = out_rms(s_poly, n, FIR_NUM_TAPS);
    const double expect = amp / sqrt(2.0);
    const double loss_db = -20.0 * log10(rms / expect);

    CHECK(loss_db < 0.5);
    CHECK(loss_db > -0.5);
}

static void test_alias_rejection(void)
{
    TEST("an out-of-band tone that would fold into the passband is >40 dB down");

    /*
     * 6000 Hz sampled at 30 kSPS and decimated to 7.5 kSPS folds to
     * |6000 - 7500| = 1500 Hz - squarely inside the band of interest, where
     * nothing distinguishes it from real signal. This is precisely the tone the
     * anti-alias filter exists to kill, and the one a filter-less decimator
     * passes at full amplitude.
     */
    const double amp = 1000000.0;
    fill_tone(s_in, N_IN, 6000.0, amp);
    const uint32_t n = run_polyphase(s_in, N_IN, s_poly);

    const double rms = out_rms(s_poly, n, FIR_NUM_TAPS);
    const double expect = amp / sqrt(2.0);
    const double rejection_db = -20.0 * log10((rms + 1e-9) / expect);

    printf("       measured alias rejection at 6 kHz: %.1f dB "
           "(design predicts %.1f dB worst case)\n",
           rejection_db, (double)FIR_ALIAS_REJ_DB);
    CHECK(rejection_db > 40.0);
}

static void test_no_filter_would_fail_this(void)
{
    TEST("control: naive downsampling with NO filter passes the alias at full amplitude");

    /*
     * The counter-example that gives the previous test meaning. Decimating by
     * simply keeping every 4th sample lets the 6 kHz tone through essentially
     * untouched, where it is indistinguishable from a real 1500 Hz signal.
     */
    const double amp = 1000000.0;
    fill_tone(s_in, N_IN, 6000.0, amp);

    uint32_t n = 0U;
    for (uint32_t i = FIR_DECIM_M - 1U; i < N_IN; i += FIR_DECIM_M) {
        s_ref[n] = s_in[i];
        n++;
    }

    const double rms = out_rms(s_ref, n, 0U);
    const double rejection_db = -20.0 * log10(rms / (amp / sqrt(2.0)));

    printf("       unfiltered decimation rejects only %.1f dB\n", rejection_db);
    CHECK(rejection_db < 1.0);
}

static void test_mac_count_is_four_times_cheaper(void)
{
    fir_decim_t f;
    int32_t y;

    TEST("polyphase does N MACs per OUTPUT sample, not per input sample");

    fir_decim_reset(&f);
    for (uint32_t i = 0U; i < 4000U; i++) {
        (void)fir_decim_push(&f, 0, &y);
    }

    /* Naive would be 4000 * 68; polyphase is (4000/4) * 68. */
    CHECK_EQ(f.mac_count, (4000U / FIR_DECIM_M) * FIR_NUM_TAPS);
    CHECK_EQ(f.mac_count * FIR_DECIM_M, 4000U * FIR_NUM_TAPS);
}

static void test_ready_flag_guards_the_transient(void)
{
    fir_decim_t f;
    int32_t y;

    TEST("fir_decim_ready() is false until the delay lines have filled");

    fir_decim_reset(&f);
    CHECK(!fir_decim_ready(&f));

    for (uint32_t i = 0U; i < (FIR_NUM_TAPS - 1U); i++) {
        (void)fir_decim_push(&f, 1000, &y);
        CHECK(!fir_decim_ready(&f));
    }
    (void)fir_decim_push(&f, 1000, &y);
    CHECK(fir_decim_ready(&f));
}

int main(void)
{
    test_taps_are_unity_dc_gain();
    test_dc_passes_through_unchanged();
    test_polyphase_equals_naive();
    test_golden_vector();
    test_passband_tone_survives();
    test_alias_rejection();
    test_no_filter_would_fail_this();
    test_mac_count_is_four_times_cheaper();
    test_ready_flag_guards_the_transient();
    TEST_SUMMARY();
}
